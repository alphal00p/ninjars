/// Lane-major numerical inputs of a fast-path evaluation.
///
/// For `lanes` phase-space points and `n` propagators
/// `D_i = (q + V_i)² - m_i² - mu²`:
/// - `shifts[lane * n + i]` is the real momentum `V_i`;
/// - `masses_squared[lane * n + i]` is `m_i²` (imaginary part ≤ 0);
/// - `scales_squared[lane]` is the positive squared renormalization scale;
/// - `s_matrix`, if given, holds `(V_i - V_j)²` at `lane * n * n + i * n + j`
///   (exact invariants that rounded momenta might not reproduce).
#[derive(Clone, Copy, Debug)]
pub struct FastInput<'a> {
    pub lanes: usize,
    pub shifts: &'a [RMom],
    pub masses_squared: &'a [C64],
    pub scales_squared: &'a [f64],
    pub s_matrix: Option<&'a [f64]>,
}

/// Low parts of the rescue-precision kinematics of a [`FastInput`] (same
/// lanes, same layouts): the rescue-precision value of every entry is the
/// [`FastInput`] value plus its low part here (double-double for this binary64
/// engine). Read only by [`FastAmplitude::evaluate_refined`]'s re-reduction of
/// flagged lanes ([`FastOptions::cancellation_rescue`],
/// `docs/triangle-gram-conditioning.md`, section 7); the binary64 pass never
/// reads it.
///
/// The caller supplies the rescue-precision cure of the very binary64 point of
/// the [`FastInput`]: on-shell external legs (an exactly zero invariant keeps
/// a zero low part), momentum conservation, shifts that are the exact sums of
/// the refined external momenta, invariants consistent with the refined
/// shifts. NinjaRS then applies no repair of its own (no light-like
/// projection); an inconsistent refinement degrades the rescue, never the
/// binary64 pass.
#[derive(Clone, Copy, Debug)]
pub struct FastRefinement<'a> {
    /// `shifts[lane * n + i]` low parts, as [`FastInput::shifts`].
    pub shifts: &'a [RMom],
    /// `(V_i - V_j)²` low parts, as [`FastInput::s_matrix`] (only with an
    /// `s_matrix` there). `None`: the invariants are the refined shifts'.
    pub s_matrix: Option<&'a [f64]>,
    /// `m_i²` low parts, as [`FastInput::masses_squared`]. `None`: the squared
    /// masses are exact in binary64.
    pub masses_squared: Option<&'a [C64]>,
}

/// A lazy source of rescue-precision kinematics ([`FastRefinement`]'s
/// semantics), asked only for the lanes the re-reduction takes up
/// ([`FastAmplitude::evaluate_refined_with`]).
pub trait FastRefinementSource {
    /// Fill lane `lane`'s low parts: `shifts` (`n`), `s_matrix` (`n * n`, as
    /// `FastInput::s_matrix`; when `FastInput` has none it is ignored) and
    /// `masses_squared` (`n`), all zero on entry. `false`: no refinement for
    /// this lane (the internal repairs serve it).
    fn lane(
        &self,
        lane: usize,
        shifts: &mut [RMom],
        s_matrix: &mut [f64],
        masses_squared: &mut [C64],
    ) -> bool;
}

impl FastRefinementSource for FastRefinement<'_> {
    fn lane(
        &self,
        lane: usize,
        shifts: &mut [RMom],
        s_matrix: &mut [f64],
        masses_squared: &mut [C64],
    ) -> bool {
        let n = shifts.len();
        shifts.copy_from_slice(&self.shifts[lane * n..(lane + 1) * n]);
        match self.s_matrix {
            Some(s) => s_matrix.copy_from_slice(&s[lane * n * n..(lane + 1) * n * n]),
            // The invariants of the refined shifts: flagged by NaN, which the
            // re-reduction replaces by the refined shifts' own invariants.
            None => s_matrix.fill(f64::NAN),
        }
        if let Some(m) = self.masses_squared {
            masses_squared.copy_from_slice(&m[lane * n..(lane + 1) * n]);
        }
        true
    }
}

/// Per-lane outcome of a fast-path evaluation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FastStatus {
    NotEvaluated,
    Success,
    /// A cut failed Ninja's stability checks (near-singular Gram determinant,
    /// vanishing uncut denominator expansion, ...; see
    /// [`FastOptions::relative_tolerance`]). Results are unchanged.
    ///
    /// Inherited from Ninja: two real cut momenta spanning a Euclidean plane
    /// (positive Gram determinant `k1² k2² - (k1.k2)²`) have no real massless
    /// basis, and Ninja's `Basis(k1, k2)` takes the square root of the
    /// negative `(k1.k2)² - k1² k2²` (C++ Ninja continues with NaN). Physical
    /// kinematics rarely have such planes, but random momenta do: among the
    /// many triangles and boxes of `n >= 12` propagators almost every lane
    /// has one. The generic engine handles these cuts.
    Unstable,
    /// A master integral failed for this lane. Results are unchanged.
    MasterFailed,
    /// The accumulated result is not finite. Results are unchanged.
    NonFinite,
}

/// The test that made a lane [`FastStatus::Unstable`] ([`Instability`]).
/// Non-exhaustive: later NinjaRS versions may name further tests.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum InstabilityTest {
    /// A box cut's Gram determinant of two of its shift differences.
    BoxGram,
    /// A box normal's factors (its square, `p1.e3`, `p1.e4`).
    BoxNormal,
    /// The rank n+2 box geometry (normal, centre, solutions): a vanishing or
    /// non-finite normal or Gram determinant (no quantity to compare).
    BoxGeometry,
    /// An uncut denominator at a box cut solution (each factor and their
    /// product).
    BoxCutDenominator,
    /// At rank n, an uncut line's `d0_j = 2 v.(V_j - V_first)` of the box
    /// mu expansion (each factor and their product).
    BoxMuDenominator,
    /// Above rank n, an uncut line's `d0_j` of the box mu expansion's
    /// Laurent division.
    BoxMuExpansion,
    /// A triangle cut's Gram determinant.
    TriangleGram,
    /// A triangle's Laurent expansion: an uncut line's leading coefficient
    /// `2 e3.(V_j - V_first)` or `2 e4.(V_j - V_first)`.
    TriangleExpansion,
    /// A bubble's Laurent expansion (an uncut line's leading coefficient).
    BubbleExpansion,
    /// A tadpole's Laurent expansion (an uncut line's leading coefficient).
    TadpoleExpansion,
    /// The box mu expansion's conditioning screen (`crate::conditioning`).
    BoxMuConditioning,
    /// A box or triangle cut whose two real momenta span a Euclidean plane
    /// (positive Gram determinant `k1² k2² - (k1.k2)²`): no real massless
    /// basis ([`FastStatus::Unstable`]); the generic engine handles it. A
    /// triangle without uncut lines (n = 3) is named when its lane's result
    /// is not finite.
    EuclideanPlane,
    /// A lane re-reduced by [`FastOptions::cancellation_rescue`] whose own
    /// estimate still exceeds [`FastOptions::rescue_target`].
    CancellationRescue,
}

impl InstabilityTest {
    /// The test's name in a status text.
    pub fn name(self) -> &'static str {
        match self {
            Self::BoxGram => "box Gram determinant",
            Self::BoxNormal => "box normal",
            Self::BoxGeometry => "box geometry",
            Self::BoxCutDenominator => "box uncut denominator",
            Self::BoxMuDenominator => "box mu-expansion denominator",
            Self::BoxMuExpansion => "box mu-expansion Laurent denominator",
            Self::TriangleGram => "triangle Gram determinant",
            Self::TriangleExpansion => "triangle expansion",
            Self::BubbleExpansion => "bubble expansion",
            Self::TadpoleExpansion => "tadpole expansion",
            Self::BoxMuConditioning => "box mu-expansion conditioning",
            Self::EuclideanPlane => "Euclidean-plane cut",
            Self::CancellationRescue => "cancellation rescue",
        }
    }
    /// Whether the test refuses a value above its bound
    /// ([`Self::BoxMuConditioning`], [`Self::EuclideanPlane`]) rather than
    /// one at or below it (the noise tests).
    pub fn refuses_above(self) -> bool {
        matches!(
            self,
            Self::BoxMuConditioning | Self::EuclideanPlane | Self::CancellationRescue
        )
    }
}

/// Why a lane is [`FastStatus::Unstable`] ([`take_instabilities`]): the
/// test, the tested quantity and its bound. The noise tests compare taxicab
/// norms with `max(stability_threshold, relative_tolerance x scale)`, the
/// lane failing when `value <= bound`; [`InstabilityTest::BoxMuConditioning`]
/// compares the predicted rounding error with its limit
/// `2^-BOX_MU_TARGET_BITS |finite part|` and [`InstabilityTest::EuclideanPlane`]
/// the cut's Gram determinant with 0, the lane failing when `value > bound`
/// ([`InstabilityTest::refuses_above`]). A NaN value is a tested quantity
/// that is not finite; NaN for both when the failing test compares none
/// ([`InstabilityTest::BoxGeometry`]). [`std::fmt::Display`] gives the
/// status text, found and required, e.g. `triangle Gram determinant: found
/// 0, required > 1.82e-12`. Non-exhaustive: later versions may add fields.
#[derive(Clone, Copy, Debug, PartialEq)]
#[non_exhaustive]
pub struct Instability {
    pub test: InstabilityTest,
    pub value: f64,
    pub bound: f64,
}

impl std::fmt::Display for Instability {
    /// `box normal: found 3.09e-11, required > 3.26e-8`,
    /// `box mu-expansion conditioning: predicted error 3.19e-15, allowed <= 2.36e-15`,
    /// `Euclidean-plane cut: Gram determinant 1.00e0, required <= 0`
    /// (`crate::refusal_text`).
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        use crate::refusal_text::{RefusalText, number};
        let test = self.test.name();
        if self.value.is_nan() && self.bound.is_nan() {
            return write!(f, "{test}: degenerate, no quantity to compare");
        }
        let (quantity, requirement) = match self.test {
            InstabilityTest::BoxMuConditioning => ("predicted error", "allowed <="),
            InstabilityTest::CancellationRescue => ("estimated error", "target <="),
            InstabilityTest::EuclideanPlane => ("Gram determinant", "required <="),
            _ => ("found", "required >"),
        };
        RefusalText {
            test,
            quantity,
            found: number(self.value),
            requirement,
            bound: number(self.bound),
            note: None,
        }
        .fmt(f)
    }
}

/// One lane's re-reduction by [`FastOptions::cancellation_rescue`]
/// ([`take_rescues`]). Non-exhaustive: later versions may add fields.
#[derive(Clone, Copy, Debug, PartialEq)]
#[non_exhaustive]
pub struct Rescue {
    /// The precision of the re-reduction in bits (106: double-double).
    pub precision_bits: u32,
    /// Its own relative error estimate: `2^-53` times the moduli of its terms
    /// that keep a binary64 factor plus `2^-104` times the others, over
    /// `|finite|`.
    pub estimate: f64,
    /// Whether it met [`FastOptions::rescue_target`] and was served; if not,
    /// the lane is [`FastStatus::Unstable`]
    /// ([`InstabilityTest::CancellationRescue`]).
    pub served: bool,
}

/// Integrated contribution of one lane.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct FastResult {
    /// `[finite, 1/eps, 1/eps²]`, including the rational part in `finite`.
    pub laurent: [C64; 3],
    /// Finite cut-constructible part (without the rational term).
    pub cut_constructible: C64,
    /// Finite rational part.
    pub rational: C64,
}
