//! Batched binary64 fast path for Ninja's integrand reduction.
//!
//! The generic [`crate::Amplitude`] carries arbitrary Symbolica numerical
//! domains (DoubleFloat, arbitrary precision, Dual numbers) through
//! Symbolica-generated kernels. This module is a monomorphic specialization of
//! the same Laurent reduction for ordinary binary64 inputs with real external
//! kinematics and real or complex squared masses. It follows original Ninja's
//! algorithm (Mastrolia, Mirabella, Peraro, arXiv:1203.0291, 1403.1229) cut by
//! cut, while keeping every phase-space lane of a batch together so numerator
//! and master providers receive compact batched requests.
//!
//! Results use Ninja/OneLOop Laurent order `[finite, 1/eps, 1/eps²]`.
//!
//! - [`FastAmplitude`] ports original Ninja's default `Amplitude::evaluate`
//!   (`ComplexMasses`, mu-expansion, no tests) for any `n >= 1` and
//!   `rank <= n + 1` (`Xninja.cc`), including its skip rules and stability
//!   checks. Coefficient-level subtractions are translated mechanically from
//!   Ninja (`tools/fast/translate_subtractions.py` → `subtractions.rs`).
//!   Rank `n + 2`, beyond original Ninja, is reduced by a separate engine
//!   (`engine_x2.rs`, chosen once at construction) whose coefficient-level
//!   subtractions evaluate the series definition directly
//!   (`subtractions_series_x2.rs`; the closed forms generated by
//!   `tools/fast/generate_subtractions_x2.py` → `subtractions_x2.rs` serve as
//!   the test reference); the rank <= n+1 code is unaffected by it.
//!   Lanes declared at rank n+2 whose numerator has a lower rank are reduced
//!   by the rank <= n+1 engine at that rank instead (`declared_rank.rs`;
//!   [`AtDeclaredRank`] keeps the rank n+2 engine).
//! - [`TensorNumerator`] is Ninja's/MadLoop's tensor numerator;
//!   [`MuTensorNumerator`] extends it with explicit `mu²` powers
//!   (`sum_k mu^(2k) T_k(q)`, e.g. FDH numerators carrying R2).
//! - [`GenericNumerator`] / [`GenericMasters`] adapt the generic NinjaRS
//!   provider traits; [`replay`] records providers and replays them in O(1)
//!   to time the pure reduction.

