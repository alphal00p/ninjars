//! Regenerate the opt-in denominator catalog from its existing Symbolica plans.
use std::{error::Error, fs, path::PathBuf};

use ninjars::Complex;
use ninjars_symbolica::{
    DenominatorExpansion,
    rust_codegen::{EmitOptions, RustEmitter, RustKernelExport},
};
use serde_json::json;
use symbolica::domains::{dual::HyperDual, rational::Rational};

fn main() -> Result<(), Box<dyn Error>> {
    let directory = std::env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/native_kernels/generated")
        });
    fs::create_dir_all(&directory)?;
    let mut emitter = RustEmitter::default();
    let shape = vec![vec![0, 0], vec![1, 0], vec![0, 1], vec![2, 0], vec![1, 1]];
    let structure = HyperDual::<Complex<Rational>>::new(shape.clone());
    let mut records = Vec::new();
    for (name, cut_size) in [("t2", 2), ("t3", 3)] {
        let plan = DenominatorExpansion::new(cut_size)?;
        for dual in [false, true] {
            let module = format!("{name}{}", if dual { "_dual" } else { "" });
            let generated = if dual {
                plan.export_rust_batch_dual(&structure, &mut emitter, EmitOptions::default())?
            } else {
                plan.export_rust_batch(&mut emitter, EmitOptions::default())?
            };
            let source = format!(
                "// Generated by generate_native_denominators; exact plan DenominatorExpansion::new({cut_size}), Dual={dual}.\n{}",
                generated.source
            );
            records.push(json!({"module":module,"cut_size":cut_size,"dual":dual,
                "inputs":generated.input_count,"outputs":generated.output_count,
                "instructions":generated.instruction_count,"bytes":source.len()}));
            fs::write(directory.join(format!("{module}.rs")), source)?;
        }
    }
    fs::write(directory.join("constants.rs"), emitter.constants_source())?;
    fs::write(
        directory.join("metadata.json"),
        serde_json::to_string_pretty(&json!({
            "dual_shape":shape,"plans":records,"constant_count":emitter.constants().len(),
            "algebra":"Existing DenominatorExpansion expressions and Symbolica Dualizer",
            "runtime":"oneloopmaster RustEmitter instruction-major batches; width-one scalar path"
        }))? + "\n",
    )?;
    Ok(())
}
