//! Regenerate ordinary bubble-correction kernels from their shared exact plans.
use std::{error::Error, fs, path::PathBuf};

use ninjars_symbolica::{
    BubbleSourceProjection, LaurentDivision, TriangleBubbleSubtraction,
    rust_codegen::{EmitOptions, RustEmitter, RustKernelExport},
};
use serde_json::json;

fn main() -> Result<(), Box<dyn Error>> {
    let directory = std::env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/native_kernels/generated")
        });
    fs::create_dir_all(&directory)?;
    let mut emitter = RustEmitter::default();
    let mut records = Vec::new();
    let source =
        BubbleSourceProjection::new().export_rust_batch(&mut emitter, EmitOptions::default())?;
    records.push(json!({"module":"bubble_source_projection","semantic_plan":"BubbleSourceProjection",
        "inputs":source.input_count,"outputs":source.output_count,"instructions":source.instruction_count,"bytes":source.source.len()}));
    fs::write(
        directory.join("bubble_source_projection.rs"),
        format!(
            "// Generated by generate_native_bubbles from BubbleSourceProjection.\n{}",
            source.source
        ),
    )?;
    for degree in 0..=3 {
        let division = LaurentDivision::new(3, degree + 1, 2)?;
        let correction = TriangleBubbleSubtraction::for_quotient(&division)?;
        let generated = correction.export_rust_batch(&mut emitter, EmitOptions::default())?;
        let module = format!(
            "bubble_correction_{}",
            if degree == 3 {
                "higher".to_owned()
            } else {
                format!("degree{degree}")
            }
        );
        records.push(json!({"module":module,"semantic_plan":"TriangleBubbleSubtraction::for_quotient",
            "higher_rank":division.higher_rank(),"quotient_degree":degree,"quotient_powers":format!("{:?}",division.quotient_expansion()),
            "inputs":generated.input_count,"outputs":generated.output_count,"instructions":generated.instruction_count,"bytes":generated.source.len()}));
        fs::write(
            directory.join(format!("{module}.rs")),
            format!(
                "// Generated by generate_native_bubbles from the existing exact correction, quotient degree {degree}.\n{}",
                generated.source
            ),
        )?;
    }
    fs::write(
        directory.join("bubble_constants.rs"),
        emitter.constants_source(),
    )?;
    fs::write(
        directory.join("bubble_metadata.json"),
        serde_json::to_string_pretty(&json!({
            "plans":records,"constant_count":emitter.constants().len(),"dual_generated":false,
            "algebra":"Existing BubbleSourceProjection and explicit-power TriangleBubbleSubtraction subset",
            "runtime":"oneloopmaster RustEmitter instruction-major batches with width-one scalar path"
        }))? + "\n",
    )?;
    Ok(())
}
