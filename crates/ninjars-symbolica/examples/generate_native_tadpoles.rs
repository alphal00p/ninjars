//! Export existing tadpole plans; geometry selection remains independent.
use std::{error::Error, fs, path::Path};

use ninjars::Complex;
use ninjars_symbolica::{
    TadpoleGeometryProbe, TadpoleSourceProjection,
    rust_codegen::{EmitOptions, RustEmitter, RustKernelExport},
};
use serde_json::{Value, json};
use symbolica::domains::{dual::HyperDual, rational::Rational};

fn emit(
    name: &str,
    plan: &impl RustKernelExport,
    directory: &Path,
    emitter: &mut RustEmitter,
    records: &mut Vec<Value>,
) -> Result<(), Box<dyn Error>> {
    let structure = HyperDual::<Complex<Rational>>::new(vec![
        vec![0, 0],
        vec![1, 0],
        vec![0, 1],
        vec![2, 0],
        vec![1, 1],
    ]);
    for dual in [false, true] {
        let module = format!("tadpole_{name}{}", if dual { "_dual" } else { "" });
        let generated = if dual {
            plan.export_rust_batch_dual(&structure, emitter, EmitOptions::default())?
        } else {
            plan.export_rust_batch(emitter, EmitOptions::default())?
        };
        let source = format!(
            "// Generated by generate_native_tadpoles; exact tadpole plan {name}, Dual={dual}.\n{}",
            generated.source
        );
        records.push(json!({"module":module,"dual":dual,
            "inputs":generated.input_count,"outputs":generated.output_count,
            "instructions":generated.instruction_count,"bytes":source.len()}));
        fs::write(directory.join(format!("{module}.rs")), source)?;
    }
    Ok(())
}

fn main() -> Result<(), Box<dyn Error>> {
    let directory = std::env::args_os()
        .nth(1)
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| {
            Path::new(env!("CARGO_MANIFEST_DIR")).join("src/native_kernels/generated")
        });
    fs::create_dir_all(&directory)?;
    let mut emitter = RustEmitter::default();
    let mut records = Vec::new();
    for (name, source_size) in [("triangle_projection", 3), ("bubble_projection", 2)] {
        emit(
            name,
            &TadpoleSourceProjection::new(source_size)?,
            &directory,
            &mut emitter,
            &mut records,
        )?;
    }
    emit(
        "geometry_probe",
        &TadpoleGeometryProbe::new(),
        &directory,
        &mut emitter,
        &mut records,
    )?;
    fs::write(
        directory.join("tadpole_constants.rs"),
        emitter.constants_source(),
    )?;
    fs::write(
        directory.join("tadpole_metadata.json"),
        serde_json::to_string_pretty(&json!({
            "dual_shape":[[0,0],[1,0],[0,1],[2,0],[1,1]],
            "plans":records,"constant_count":emitter.constants().len(),
            "algebra":"Existing tadpole source-axis and reference-probe expressions; Symbolica Dualizer",
            "runtime":"oneloopmaster RustEmitter instruction-major batches; width-one scalar path",
            "production_dispatch":{
                "source_projections":"opt-in native ordinary and supported ordered Dual shape",
                "geometry_probe":"opt-in native geometry provider; ordinary and supported ordered Dual shape"
            }
        }))? + "\n",
    )?;
    Ok(())
}
