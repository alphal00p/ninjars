//! Export the exact guarded n5/r4 bodies through the shared oneloopmaster emitter.
use std::{error::Error, fs, path::PathBuf};

use ninjars::Complex;
use ninjars_symbolica::rust_codegen::{
    EmitOptions, RankSpecializedCorrectionPlan, RustEmitter, RustKernelExport,
};
use serde_json::json;
use symbolica::domains::{dual::HyperDual, rational::Rational};

fn main() -> Result<(), Box<dyn Error>> {
    let directory = std::env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/native_kernels/generated")
        });
    fs::create_dir_all(&directory)?;
    let shape = vec![vec![0, 0], vec![1, 0], vec![0, 1], vec![2, 0], vec![1, 1]];
    let structure = HyperDual::<Complex<Rational>>::new(shape.clone());
    let mut emitter = RustEmitter::default();
    let mut records = Vec::new();
    use RankSpecializedCorrectionPlan::*;
    for (module, plan, dimensions) in [
        (
            "rank_triangle_to_bubble_n5_r4",
            TriangleToBubbleN5R4,
            (28, 3),
        ),
        (
            "rank_triangle_to_tadpole_n5_r4",
            TriangleToTadpoleN5R4,
            (25, 1),
        ),
        ("rank_bubble_to_tadpole_n5_r4", BubbleToTadpoleN5R4, (24, 1)),
    ] {
        for dual in [false, true] {
            let generated = if dual {
                plan.export_rust_batch_dual(&structure, &mut emitter, EmitOptions::default())?
            } else {
                plan.export_rust_batch(&mut emitter, EmitOptions::default())?
            };
            let components = if dual { shape.len() } else { 1 };
            assert_eq!(
                (generated.input_count, generated.output_count),
                (dimensions.0 * components, dimensions.1 * components)
            );
            let module = format!("{module}{}", if dual { "_dual" } else { "" });
            let source = format!(
                "// Generated by generate_native_rank_specializations; semantic plan {}, Dual={dual}.\n{}",
                plan.semantic_id(),
                generated.source
            );
            records.push(
                json!({"module":module,"semantic_plan":plan.semantic_id(),"dual":dual,
                "inputs":generated.input_count,"outputs":generated.output_count,
                "instructions":generated.instruction_count,"bytes":source.len()}),
            );
            fs::write(directory.join(format!("{module}.rs")), source)?;
        }
    }
    fs::write(
        directory.join("rank_specialization_constants.rs"),
        emitter.constants_source(),
    )?;
    fs::write(
        directory.join("rank_specialization_metadata.json"),
        serde_json::to_string_pretty(&json!({
            "dual_shape":shape,"plans":records,"constant_count":emitter.constants().len(),
            "algebra":"Same Symbolica residue-projection zero masks, literal replacement and explicit head selection as guarded interpreted stages",
            "runtime":"oneloopmaster RustEmitter instruction-major batches with width-one scalar path",
            "guard":"All structural-zero components in every active source-kind row; whole-kind generic fallback"
        }))? + "\n",
    )?;
    Ok(())
}
