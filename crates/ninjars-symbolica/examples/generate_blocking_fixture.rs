//! Regenerate a test-only lazy shared-helper fixture with the existing emitter.
use ninjars::Complex;
use ninjars_symbolica::rust_codegen::{EmitOptions, RustEmitter};
use std::{error::Error, fs, path::PathBuf};
use symbolica::{
    atom::{Atom, AtomCore},
    domains::rational::Rational,
    evaluate::{ExpressionEvaluator, FunctionRegistrationOptions, InliningPolicy},
    parse, symbol,
};
fn main() -> Result<(), Box<dyn Error>> {
    let directory = std::env::args_os()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src/native_blocking_fixture")
        });
    fs::create_dir_all(&directory)?;
    let exact: ExpressionEvaluator<Complex<Rational>> = Atom::evaluator_multiple(
        &[
            parse!("if(c,blocking_probe::inverse(x),blocking_probe::inverse(y))"),
            parse!("if(c,x,y)"),
        ],
        &[parse!("c"), parse!("x"), parse!("y")],
    )
    .add_function_with_options(
        symbol!("blocking_probe::inverse"),
        vec![symbol!("a")],
        parse!("1/a"),
        FunctionRegistrationOptions::new().inlining(InliningPolicy::Never),
    )?
    .cores(1)
    .build()?;
    let mut emitter = RustEmitter::default();
    let output = emitter.emit_batch(exact, EmitOptions::default())?;
    fs::write(
        directory.join("body.rs"),
        format!(
            "// Generated by generate_blocking_fixture; do not edit.\n{}",
            output.source
        ),
    )?;
    fs::write(directory.join("constants.rs"), emitter.constants_source())?;
    println!(
        "{}",
        serde_json::json!({"inputs":output.input_count,"outputs":output.output_count,"instructions":output.instruction_count,"helpers":output.helper_count})
    );
    Ok(())
}
