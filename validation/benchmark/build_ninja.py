#!/usr/bin/env python3
"""Build original Ninja (references/ninja @05fb0d3) benchmark variants.

Every variant is configured from a fresh copy of the unchanged Ninja checkout
(the instrumented variant additionally runs instrument_ninja.py on its copy) in
<out>/ninja-<variant>/{ninja-source,ninja-build,install}. OneLOop is compiled
once per OneLOop version in <out>/oneloop-<version>/. The install prefix has
the layout MadGraph expects for 'ninja = <prefix>/lib' (libninja.a, a
libavh_olo.a symlink, ../include/mninja.mod, ../bin/ninja-config).

Common policy: static library, --disable-autoflags (flags are explicit),
--disable-avholo_cache (no master-integral cache), higher rank (X1RANK) on,
no quadninja, no -march, no fast-math, gfortran -O3 for OneLOop and the Ninja
Fortran wrappers. The nix compiler-wrapper hardening flags are disabled
(NIX_HARDENING_ENABLE='') so the effective flags are exactly the listed ones
(plus nixpkgs gcc's default -fno-omit-frame-pointer/-mno-omit-leaf-frame-pointer).

  python3 validation/benchmark/build_ninja.py [--variants ...] [--jobs 24]
"""
import argparse
import hashlib
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import time

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
MG = ROOT / "references/MG5_aMC_v3_7_0"

ONELOOP = {
    # MadGraph's HEPTools OneLOop (generated by its create.py with QPKIND=16):
    # the library MG5_aMC links with its own Ninja installation. Its module
    # names (avh_olo, avh_olo_dp, ...) do not clash with the renamed copies
    # inside CutTools (avh_olo_forCutTools) and IREGI (avh_olo_forIREGI).
    "3.6": {"sources": [MG / "HEPTools/oneloop/OneLOop-3.6/avh_olo.f90"]},
    # OneLOop-3.4 copy distributed with IREGI plus a module alias, exactly as
    # target/reference-uncached-v2 (validation/reference/build.py).
    "3.4": {"sources": [MG / "vendor/IREGI/src/oneloop/avh_olo_foriregi.f90",
                        ROOT / "validation/reference/avh_olo_alias.f90"]},
}

VARIANTS = {
    "o3": {"cxxflags": "-O3 -DNDEBUG", "oneloop": "3.6", "instrument": False},
    "o3-fortranrules": {"cxxflags": "-O3 -DNDEBUG -fcx-fortran-rules", "oneloop": "3.6",
                        "instrument": False},
    "o3-fortranrules-instr": {"cxxflags": "-O3 -DNDEBUG -fcx-fortran-rules", "oneloop": "3.6",
                              "instrument": True},
    "o3-ol34": {"cxxflags": "-O3 -DNDEBUG", "oneloop": "3.4", "instrument": False},
}
FCFLAGS = "-O3"
ONELOOP_FFLAGS = ["-O3", "-fPIC"]


def sha256(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def environment():
    env = dict(os.environ)
    env["NIX_HARDENING_ENABLE"] = ""
    return env


def run(command, cwd, commands, log=None):
    command = [str(c) for c in command]
    print("+", " ".join(command), flush=True)
    commands.append({"argv": command, "cwd": str(cwd)})
    start = time.time()
    if log is None:
        subprocess.run(command, cwd=cwd, check=True, env=environment())
    else:
        with open(log, "a") as handle:
            handle.write("+ " + " ".join(command) + "\n")
            handle.flush()
            subprocess.run(command, cwd=cwd, check=True, env=environment(),
                           stdout=handle, stderr=subprocess.STDOUT)
    commands[-1]["seconds"] = round(time.time() - start, 3)


def tool_version(name):
    return subprocess.check_output([name, "--version"], text=True).splitlines()[0]


def build_oneloop(out, version, jobs):
    directory = out / f"oneloop-{version}"
    record = directory / "oneloop.json"
    library = directory / "libavh_olo.a"
    if record.exists() and library.exists():
        data = json.loads(record.read_text())
        if data["library_sha256"] == sha256(library):
            return data
    if directory.exists():
        shutil.rmtree(directory)
    directory.mkdir(parents=True)
    commands = []
    sources = []
    for source in ONELOOP[version]["sources"]:
        shutil.copy2(source, directory / source.name)
        sources.append({"origin": str(source), "sha256": sha256(source)})
    names = [s.name for s in ONELOOP[version]["sources"]]
    run(["gfortran", *ONELOOP_FFLAGS, "-c", *names], directory, commands)
    run(["ar", "rcs", "libavh_olo.a", *[pathlib.Path(n).with_suffix(".o").name for n in names]],
        directory, commands)
    data = {"version": version, "sources": sources, "commands": commands,
            "fflags": ONELOOP_FFLAGS, "fortran_compiler": tool_version("gfortran"),
            "library_sha256": sha256(library)}
    record.write_text(json.dumps(data, indent=2) + "\n")
    return data


def config_flags(path):
    contents = path.read_text()
    enabled = lambda name: bool(re.search(r"^\s*#\s*define\s+" + name + r"\s+1\b", contents, re.M))
    return {"config_sha256": sha256(path),
            "NINJA_USE_ONELOOP": enabled("NINJA_USE_ONELOOP"),
            "NINJA_USE_ONELOOP_WITH_CACHE": enabled("NINJA_USE_ONELOOP_WITH_CACHE"),
            "NINJA_X1RANK": enabled("NINJA_X1RANK"),
            "QUADNINJA": enabled("QUADNINJA")}


def effective_compile_line(log, source):
    for line in pathlib.Path(log).read_text().splitlines():
        if source in line and ("g++" in line or "gfortran" in line) and " -c " in line:
            return line.strip()
    return None


def build_variant(out, name, jobs, oneloop):
    spec = VARIANTS[name]
    directory = out / f"ninja-{name}"
    if directory.exists():
        shutil.rmtree(directory)
    directory.mkdir(parents=True)
    log = directory / "build.log"
    commands = []
    source = directory / "ninja-source"
    shutil.copytree(ROOT / "references/ninja", source, ignore=shutil.ignore_patterns(".git"))
    if spec["instrument"]:
        run([sys.executable, HERE / "instrument_ninja.py", source], directory, commands, log)
    run(["autoreconf", "-fi"], source, commands, log)
    build = directory / "ninja-build"
    build.mkdir()
    prefix = directory / "install"
    olo_dir = out / f"oneloop-{spec['oneloop']}"
    run([source / "configure", f"--prefix={prefix}", "--disable-shared", "--disable-autoflags",
         "--disable-gosam", "--enable-higher_rank", "--disable-avholo_cache",
         f"--with-avholo=-L{olo_dir} -lavh_olo", f"FCINCLUDE=-I{olo_dir}",
         f"CXXFLAGS={spec['cxxflags']}", f"FCFLAGS={FCFLAGS}"], build, commands, log)
    config = config_flags(build / "config.h")
    if (not config["NINJA_USE_ONELOOP"] or config["NINJA_USE_ONELOOP_WITH_CACHE"]
            or not config["NINJA_X1RANK"] or config["QUADNINJA"]):
        raise RuntimeError(f"unexpected Ninja configuration {config}")
    run(["make", "-C", "src", "-j", str(jobs), "libninja.la"], build, commands, log)
    # Fortran module files, ninja-config and installation (serial: module order).
    run(["make"], build, commands, log)
    run(["make", "install"], build, commands, log)
    lib = prefix / "lib"
    link = lib / "libavh_olo.a"
    if link.exists() or link.is_symlink():
        link.unlink()
    link.symlink_to(olo_dir / "libavh_olo.a")
    if not (prefix / "include/mninja.mod").exists():
        raise RuntimeError("mninja.mod was not installed")
    quad = subprocess.run([prefix / "bin/ninja-config", "-quadsupport"], capture_output=True,
                          text=True).stdout.strip()
    return {
        "variant": name,
        "cxxflags": spec["cxxflags"], "fcflags": FCFLAGS,
        "instrumented": spec["instrument"],
        "oneloop_version": spec["oneloop"],
        "oneloop_library": str(olo_dir / "libavh_olo.a"),
        "oneloop_library_sha256": oneloop["library_sha256"],
        "prefix": str(prefix),
        "madgraph_ninja_dir": str(lib),
        "configuration": config,
        "ninja_config_quadsupport": quad,
        "commands": commands,
        "effective_compile_lines": {
            "ninja.cc": effective_compile_line(log, "ninja.cc"),
            "avholo_wrapper.F90": effective_compile_line(log, "avholo_wrapper.F90"),
        },
        "library_sha256": {"libninja.a": sha256(lib / "libninja.a"),
                           "libavh_olo.a": sha256(link)},
        "instrumentation_sources_sha256": (
            {p.name: sha256(p) for p in [HERE / "instrument_ninja.py", HERE / "ninja_bench_timers.hh"]}
            if spec["instrument"] else None),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--variants", nargs="+", default=list(VARIANTS), choices=list(VARIANTS))
    parser.add_argument("--jobs", type=int, default=24)
    parser.add_argument("--out", type=pathlib.Path, default=ROOT / "target/benchmark")
    parser.add_argument("--record", type=pathlib.Path, default=HERE / "ninja-builds.json")
    args = parser.parse_args()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    record = json.loads(args.record.read_text()) if args.record.exists() else {}
    ninja_commit = subprocess.check_output(["git", "-C", ROOT / "references/ninja", "rev-parse", "HEAD"],
                                           text=True).strip()
    dirty = bool(subprocess.check_output(["git", "-C", ROOT / "references/ninja", "status", "--porcelain"],
                                         text=True).strip())
    record.update({
        "schema": "ninjars-reference-ninja-builds-v1",
        "ninja_commit": ninja_commit, "ninja_checkout_dirty": dirty,
        "cxx_compiler": tool_version("g++"), "fortran_compiler": tool_version("gfortran"),
        "environment": {"NIX_HARDENING_ENABLE": "", "note":
                        "nix wrapper hardening disabled; nixpkgs gcc still defaults to "
                        "-fno-omit-frame-pointer -mno-omit-leaf-frame-pointer, -march=x86-64 -mtune=generic"},
        "build_root": str(out),
    })
    record.setdefault("oneloop", {})
    record.setdefault("variants", {})
    built = {}
    for name in args.variants:
        version = VARIANTS[name]["oneloop"]
        if version not in built:
            built[version] = build_oneloop(out, version, args.jobs)
            record["oneloop"][version] = built[version]
        record["variants"][name] = build_variant(out, name, args.jobs, built[version])
        args.record.write_text(json.dumps(record, indent=2) + "\n")
    print(args.record)


if __name__ == "__main__":
    main()
